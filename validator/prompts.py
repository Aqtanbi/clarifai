def critic_prompt(numbered_doc: str, reqs: list[dict], findings: list[dict]) -> str:
    return f"""Задача: ты — независимый рецензент отчёта о ревью требований. Проверь каждую находку по документу.

Удали (action="drop") находку, если:
- утверждение неверно: то, что якобы отсутствует, в документе есть; или цитата/интерпретация искажает смысл;
- она общая, без конкретики («можно уточнить»);
- она дублирует другую находку (оставь более точную; в reason укажи id оставленной);
- это вкусовщина, не нарушающая ни одного критерия.
Находки с source="simulation" удаляй ТОЛЬКО если модель явно неверно реализовала правило (объясни, где).
Иначе action="keep". Можешь скорректировать severity (critical|major|minor) по правилам:
{SEVERITY_GUIDE}

Затем вынеси итог (verdict):
- ready: "да" (можно начинать разработку и тестирование), "условно" (можно начать с оговорками, критичные дефекты локальны), "нет" (нельзя до исправления);
- summary: 2–4 предложения, почему, со ссылкой на конкретные требования;
- top_fixes: 3–7 действий, что исправить в первую очередь, по убыванию важности, с id находок.

Схема ответа:
{{"decisions":[{{"id":"F-001","action":"keep","severity":"critical","reason":"..."}}],
 "verdict":{{"ready":"нет","summary":"...","top_fixes":[{{"finding_ids":["F-001","F-007"],"action":"..."}}]}}}}

Требования (JSON):
{json.dumps(reqs, ensure_ascii=False, indent=1)}

Находки (JSON):
{json.dumps(findings, ensure_ascii=False, indent=1)}

Документ (строки пронумерованы):
<<<
{numbered_doc}
>>>"""
