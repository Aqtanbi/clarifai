def profile_context(profile) -> str:
    """Текстовый блок профиля для подстановки в промпты следующих этапов."""
    if not profile:
        return ""
    checks = "\n".join(f"  - [{c.area}] {c.check}" + (f" — {c.why}" if c.why else "") for c in profile.focus_checks)
    return f"""Профиль документа (составлен на предыдущем этапе):
- тип: {profile.doc_type}; предметная область: {profile.domain}
- структура: {profile.structure}
- нумерация требований: {profile.numbering}
- определённые термины: {", ".join(profile.defined_terms) or "нет"}
Чек-лист рисков для ЭТОГО документа (используй его, но не ограничивайся им):
{checks}
"""


