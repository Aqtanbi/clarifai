SIM_CONTRACT = """Контракт кода:
- Python 3.10+, ТОЛЬКО стандартная библиотека и только модули: json, datetime, decimal, fractions, math, dataclasses, enum, typing, itertools, collections, functools, re. Без файлов, сети, os, sys, subprocess, eval/exec, input. Часовые пояса — через datetime.timezone(timedelta(hours=N)), без zoneinfo.
- Реализуй каждое правило из требований отдельной функцией; в docstring — id требования и цитата.
- Вариант "literal" — буквальное прочтение текста. Если правило допускает несколько прочтений (неоднозначность), добавь альтернативные варианты (literal=false) с описанием.
- Сценарии: (а) каждый критерий приёмки/пример из документа; (б) граничные значения (на границе, ±1 единица); (в) сценарии на стыке правил, где два требования могут дать разный результат (смена настроек, повторы, отмены, переходы периодов, ошибки).
- Каждая проверка (check) сравнивает expected (что утверждает источник: критерий приёмки или требование, source = его id в документе, quote = дословная цитата источника) с actual (что получается по модели остальных правил). ok = (expected == actual). Если два требования дают разный результат — check с expected по одному и actual по другому, source = "A vs B".
- В конце программа печатает в stdout РОВНО ОДИН JSON:
{"variants":[{"name":"literal","literal":true,"description":"...","basis_quote":"..."}],
 "results":[{"scenario_id":"S-01","title":"...","variant":"literal","checks":[{"source":"КП-1","quote":"...","expected":"...","actual":"...","ok":true}]}]}
- Значения expected/actual — короткие строки (например "push=1, итог=50000").

Пример стиля (другая предметная область):
def rule_fine(days_late: int) -> int:
    \"\"\"П-2: «Штраф 10 руб. за каждый полный день просрочки»\"\"\"
    return 10 * days_late"""


