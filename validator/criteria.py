    Criterion("UNA", "Однозначность", "ISO 29148 5.2.5 c); IEEE 830 4.3.2", "Можно ли понять только одним способом? Определены ли термины, единицы, часовые пояса, граничные случаи, нет ли размытых слов?"),
    Criterion("CMP", "Полнота", "ISO 29148 5.2.5 d); IEEE 830 4.3.3", "Достаточно ли информации для реализации: все ли условия, исключения, ошибки, значения по умолчанию определены?"),
