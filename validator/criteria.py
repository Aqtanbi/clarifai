ALL = {c.code: c for c in INDIVIDUAL + SET}
INDIVIDUAL_CODES = [c.code for c in INDIVIDUAL]
SET_CODES = [c.code for c in SET]

SEVERITY = {
    "critical": "Критично",
    "major": "Существенно",
    "minor": "Незначительно",
}
SEVERITY_ORDER = {"critical": 0, "major": 1, "minor": 2}


def criteria_prompt(criteria: list[Criterion]) -> str:
    return "\n".join(f"- {c.code} — {c.name} ({c.source}): {c.question}" for c in criteria)


def label(code: str) -> str:
    c = ALL.get(code)
    return f"{c.name} ({c.source})" if c else code
